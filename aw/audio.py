# one-line client config for apps: never autospawn a real PulseAudio
PULSE_CLIENT_CONF = "autospawn = no\n"


class AudioError(Exception):
    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code, self.message = code, message


def have_pipewire() -> bool:
    import shutil
    return all(shutil.which(b) for b in ("pipewire", "pipewire-pulse", "wireplumber", "pw-cat"))


def write_configs(audio_dir: str) -> Dict[str, str]:
    os.makedirs(audio_dir, mode=0o700, exist_ok=True)
    out = {}
    for name, body in (("pipewire.conf", PIPEWIRE_CONF), ("pipewire-pulse.conf", PULSE_CONF),
                       ("pulse-client.conf", PULSE_CLIENT_CONF)):
        p = os.path.join(audio_dir, name)
        with open(p, "w") as f:
            f.write(body)
        out[name] = p
    for sub in ("xdg/config", "xdg/state", "xdg/cache", "xdg/data"):
        os.makedirs(os.path.join(audio_dir, sub), mode=0o700, exist_ok=True)
    return out


def daemon_env(ws_dir: str, rt: str, path: str, bus_address: str) -> Dict[str, str]:
    """Environment for the audio daemons: everything private, no system bus (so no rtkit/logind)."""
    a = os.path.join(ws_dir, "audio")
    return {"PATH": path, "HOME": a, "XDG_RUNTIME_DIR": rt, "XDG_CONFIG_HOME": os.path.join(a, "xdg/config"),
            "XDG_STATE_HOME": os.path.join(a, "xdg/state"), "XDG_CACHE_HOME": os.path.join(a, "xdg/cache"),
            "XDG_DATA_HOME": os.path.join(a, "xdg/data"), "DBUS_SESSION_BUS_ADDRESS": bus_address,
            "DBUS_SYSTEM_BUS_ADDRESS": "unix:path=/nonexistent", "LANG": "C.UTF-8",
            "PIPEWIRE_REMOTE": os.path.join(rt, "pipewire-0")}


def client_env(rt: str, enabled: bool, audio_dir: str) -> Dict[str, str]:
    """Variables the launcher adds to every app: pulse goes to the workspace's own server, or nowhere."""
    sock = os.path.join(rt, "pulse", "native" if enabled else "native-disabled")
    return {"PULSE_SERVER": f"unix:{sock}", "PULSE_CLIENTCONFIG": os.path.join(audio_dir, "pulse-client.conf")}


# ---- analysis of recordings ----------------------------------------------------------------------

def analyse_pcm16(frames: bytes, channels: int = CHANNELS, rate: int = RATE) -> Dict[str, Any]:
    """Peak, RMS (dBFS) and tone frequency of interleaved s16le. `tone_hz` is a zero-crossing estimate: only
    meaningful when the signal is a single tone (a test signal), null for silence."""
    n = len(frames) // 2
    if n == 0:
        return {"frames": 0, "peak": 0.0, "rms": 0.0, "rms_dbfs": None, "tone_hz": None}
    samples = struct.unpack(f"<{n}h", frames[:n * 2])
    mono = samples[0::channels] if channels > 1 else samples
    peak = max(abs(s) for s in samples) / 32768.0
    rms = math.sqrt(sum(s * s for s in samples) / n) / 32768.0
    tone = None
    if rms > 1e-3 and len(mono) > 2048:
        thr = 0.05 * 32768 * peak
        crossings, first, last, state = 0, None, None, 0
        for i, x in enumerate(mono):
            if x > thr and state <= 0:
                if state < 0:                      # negative -> positive: one period boundary
                    crossings += 1
                    first = i if first is None else first
                    last = i
                state = 1
            elif x < -thr and state >= 0:
                state = -1
        if crossings >= 3 and last > first:
            tone = round((crossings - 1) * rate / (last - first), 1)
    return {"frames": len(mono), "peak": round(peak, 4), "rms": round(rms, 5),
            "rms_dbfs": round(20 * math.log10(rms), 1) if rms > 0 else None, "tone_hz": tone}


def write_wav(path: str, pcm: bytes, channels: int = CHANNELS, rate: int = RATE) -> None:
    with wave.open(path, "wb") as w:
        w.setnchannels(channels)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(pcm)


class PrivateAudio:
    """The three daemons of one workspace. Process creation is delegated to the manager (`spawn`), so they
    live in the workspace's systemd slice and die with it."""

    def __init__(self, ws_dir: str, rt: str):
        self.ws_dir, self.rt = ws_dir, rt
        self.dir = os.path.join(ws_dir, "audio")
        self.pids: Dict[str, int] = {}

    @property
    def pw_socket(self) -> str:
        return os.path.join(self.rt, "pipewire-0")

    @property
    def pulse_socket(self) -> str:
        return os.path.join(self.rt, "pulse", "native")

    def start(self, spawn, env: Dict[str, str], timeout: float = 8.0) -> None:
        """spawn(unit, env, argv, stdout) -> Popen."""
        cfg = write_configs(self.dir)
        log = open(os.path.join(self.dir, "audio.log"), "ab")
        p = spawn("pipewire", env, ["pipewire", "-c", cfg["pipewire.conf"]], log)
        self.pids["pipewire"] = p.pid
        self._wait(lambda: os.path.exists(self.pw_socket), timeout, "pipewire socket")
        w = spawn("wireplumber", env, ["wireplumber", "--profile", "policy"], log)
        self.pids["wireplumber"] = w.pid
        pp = spawn("pipewire-pulse", env, ["pipewire-pulse", "-c", cfg["pipewire-pulse.conf"]], log)
        self.pids["pipewire-pulse"] = pp.pid
        self._wait(lambda: os.path.exists(self.pulse_socket), timeout, "pulse socket")
        # the policy manager must have registered before the first stream connects
        self._wait(lambda: self.default_sink(env) is not None, timeout, "default sink")

    @staticmethod
    def _wait(pred, timeout: float, what: str):
        end = time.monotonic() + timeout
        while time.monotonic() < end:
            if pred():
                return
            time.sleep(0.05)
        raise AudioError("E_AUDIO_START", f"private audio did not come up ({what})")

    # ---- inspection (always against the workspace's own socket)
    def _run(self, env: Dict[str, str], argv: List[str], timeout: float = 5.0) -> str:
        r = subprocess.run(["/usr/bin/env", "-i"] + [f"{k}={v}" for k, v in env.items()] + argv,
                           capture_output=True, text=True, timeout=timeout)
        return r.stdout

    def dump(self, env: Dict[str, str]) -> List[Dict[str, Any]]:
        try:
            return json.loads(self._run(env, ["pw-dump"]) or "[]")
        except (ValueError, subprocess.SubprocessError, OSError):
            return []

    def default_sink(self, env: Dict[str, str]) -> Optional[str]:
        for o in self.dump(env):
            if o.get("type", "").endswith("Metadata"):
                for m in o.get("metadata", []):
                    if m.get("key") == "default.audio.sink":
                        v = m.get("value")
                        return v.get("name") if isinstance(v, dict) else None
        return None

    def streams(self, env: Dict[str, str]) -> List[Dict[str, Any]]:
        out = []
        for o in self.dump(env):
            if o.get("type", "").endswith(":Node"):
                p = (o.get("info") or {}).get("props") or {}
                cls = p.get("media.class", "")
                if cls.startswith("Stream/"):
                    out.append({"id": o["id"], "class": cls, "app": p.get("application.name") or p.get("node.name"),
                                "media_name": p.get("media.name"), "state": (o.get("info") or {}).get("state")})
        return out

    def info(self, env: Dict[str, str]) -> Dict[str, Any]:
        alive = {k: os.path.exists(f"/proc/{p}") for k, p in self.pids.items()}
        return {"mode": "private", "sink": SINK, "default_sink": self.default_sink(env), "daemons": alive,
                "streams": self.streams(env), "pulse_server": f"unix:{self.pulse_socket}"}

    # ---- capture
    def record(self, env: Dict[str, str], seconds: float, path: Optional[str]) -> Dict[str, Any]:
        seconds = float(seconds)
        if not (0.1 <= seconds <= 120):
            raise AudioError("E_BAD_ARGS", "seconds must be between 0.1 and 120")
        n = int(seconds * RATE)
        argv = ["pw-cat", "-r", "-a", "--format", "s16", "--rate", str(RATE), "--channels", str(CHANNELS),
                "--target", SINK, "-P", "stream.capture.sink=true", "-n", str(n), "-"]
        p = subprocess.Popen(["/usr/bin/env", "-i"] + [f"{k}={v}" for k, v in env.items()] + argv,
                             stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, start_new_session=True)
        want = n * CHANNELS * 2
        buf = bytearray()
        deadline = time.monotonic() + seconds + 5
        try:
            while len(buf) < want and time.monotonic() < deadline:
                chunk = p.stdout.read(min(65536, want - len(buf)))
                if not chunk:
                    break
                buf += chunk
        finally:
            try:
                os.killpg(p.pid, signal.SIGTERM)
            except (ProcessLookupError, PermissionError):
                pass
            try:
                p.wait(3)
            except subprocess.TimeoutExpired:
                os.killpg(p.pid, signal.SIGKILL)
        pcm = bytes(buf)
        res = analyse_pcm16(pcm)
        res.update({"rate": RATE, "channels": CHANNELS, "seconds": round(len(pcm) / (RATE * CHANNELS * 2), 3)})
        if path:
            write_wav(path, pcm)
            res["path"] = path
        return res
