"""Per-workspace audio: a private PipeWire graph with a null sink.

Layout (all inside the workspace's private runtime dir, `<ws>/rt`, so the host's PipeWire/Pulse sockets are
not discoverable and nothing can reach the host speakers unless routing is configured explicitly):

    pipewire          core, a null sink `aw-sink` (the workspace's only "speaker") + its monitor
    wireplumber       policy only (`--profile policy`): links app streams to the null sink. No ALSA,
                      Bluetooth or V4L2 monitor is loaded, so the workspace never opens /dev/snd.
    pipewire-pulse    PulseAudio protocol server (`<rt>/pulse/native`) for Chrome, Firefox, VLC, ...

Apps find them through the workspace's private XDG_RUNTIME_DIR; the launcher also sets PULSE_SERVER
explicitly (pointing at the workspace's own socket, or at a dead path when audio is off) so that libpulse
never autospawns a real PulseAudio.

Capturing: `record()` reads the monitor of the null sink (what the workspace "played") with pw-cat.
Routing to the host: off by default; `RouteToHost` pipes that monitor into the host PipeWire on explicit
request (see docs/audio.md).
"""
from __future__ import annotations

import json
import math
import os
import signal
import struct
import subprocess
import time
import wave
from typing import Any, Dict, List, Optional

SINK = "aw-sink"
RATE = 48000
CHANNELS = 2

